import json
import asyncio
import os
import sys

sys.path.append(os.path.join(os.path.dirname(__file__), ".."))

import httpx
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel, Field
from app.config import settings

class RAGScore(BaseModel):
    faithfulness: int = Field(description="1 if the answer is completely supported by the context without hallucination, else 0.")
    answer_relevance: int = Field(description="1 if the answer directly addresses the question, else 0.")
    context_precision: int = Field(description="1 if the retrieved context contains the information needed to answer the question, else 0. For OUT_OF_DOMAIN, 1 if context correctly doesn't force a wrong answer.")
    reasoning: str = Field(description="A brief explanation for the scores.")

async def evaluate_rag():
    with open("tests/golden_dataset.json", "r") as f:
        dataset = json.load(f)
        
    llm_judge = ChatOpenAI(
        model="google/gemini-2.5-flash",
        api_key=settings.openrouter_api_key,
        base_url="https://openrouter.ai/api/v1",
        temperature=0.0
    ).with_structured_output(RAGScore)
    
    system_prompt = """You are an impartial AI Judge evaluating a RAG pipeline for an AI Engineer's portfolio bot.
Given a Question, the Retrieved Context, the Expected Answer, and the Actual Answer generated by the system, score the system's performance.
Use the JSON schema to output exactly three binary scores (1 or 0) and your reasoning."""

    results = []
    
    print(f"Starting Evaluation on {len(dataset)} queries...\n")
    
    for item in dataset:
        question = item["question"]
        expected = item["expected_answer"]
        
        # 1. Run the RAG pipeline via HTTP endpoint to avoid Qdrant DB Locks
        try:
            async with httpx.AsyncClient(timeout=60.0) as client:
                response = await client.post("http://localhost:8000/api/evaluate", json={"query": question})
                response.raise_for_status()
                data = response.json()
                
                actual_answer = data.get("actual_answer", "")
                retrieved_context = data.get("retrieved_context", "")
        except Exception as e:
            actual_answer = f"Error: {e}"
            retrieved_context = ""
            
        # 2. Judge the output
        judge_prompt = f"""
QUESTION: {question}

EXPECTED ANSWER:
{expected}

RETRIEVED CONTEXT (What the RAG system found):
{retrieved_context}

ACTUAL ANSWER (What the AI generated):
{actual_answer}
"""
        
        try:
            score = await llm_judge.ainvoke([SystemMessage(content=system_prompt), HumanMessage(content=judge_prompt)])
        except Exception as e:
            print(f"Failed to judge question '{question}': {e}")
            score = RAGScore(faithfulness=0, answer_relevance=0, context_precision=0, reasoning=f"Judge error: {e}")
            
        results.append({
            "question": question,
            "expected": expected,
            "actual": actual_answer,
            "context": retrieved_context,
            "scores": {
                "faithfulness": score.faithfulness,
                "answer_relevance": score.answer_relevance,
                "context_precision": score.context_precision
            },
            "reasoning": score.reasoning
        })
        
        print(f"✅ Evaluated: {question}")
        print(f"   Scores: F={score.faithfulness} R={score.answer_relevance} C={score.context_precision}")
        
    # Generate Markdown Report
    # Write directly to the artifacts directory so the AI agent can read it
    artifact_path = "/Users/chandrug/.gemini/antigravity-ide/brain/634640e7-0904-4c0c-af2c-b9a6d9087a76/rag_evaluation_results.md"
    report = "# RAG Evaluation Analysis Sheet\n\n"
    report += "| Question | Faithfulness | Relevance | Context Precision | Reasoning |\n"
    report += "|---|---|---|---|---|\n"
    
    total_f = total_r = total_c = 0
    
    for r in results:
        s = r["scores"]
        total_f += s["faithfulness"]
        total_r += s["answer_relevance"]
        total_c += s["context_precision"]
        
        q = r['question'].replace('|', '')
        reasoning = r['reasoning'].replace('\n', ' ').replace('|', '')
        report += f"| {q} | {s['faithfulness']} | {s['answer_relevance']} | {s['context_precision']} | {reasoning} |\n"
        
    n = len(results)
    report += "\n## Averages\n"
    report += f"- **Faithfulness (Anti-Hallucination):** {(total_f/n)*100:.1f}%\n"
    report += f"- **Answer Relevance:** {(total_r/n)*100:.1f}%\n"
    report += f"- **Context Precision:** {(total_c/n)*100:.1f}%\n"
    
    with open(artifact_path, "w") as f:
        f.write(report)
        
    print(f"\nEvaluation complete! Report saved to {artifact_path}")

if __name__ == "__main__":
    asyncio.run(evaluate_rag())
